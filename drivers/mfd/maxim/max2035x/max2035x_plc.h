struct max2035x_plc_irq_data {
	struct max2035x_plc *plc;
	unsigned int event;
};

struct max2035x_plc {
	struct device *dev;
	struct max2035x *chip;
	struct regmap *ram_regmap;
	struct dentry *debugfs_root;

	const struct max2035x_plc_irq_map *irq_map;
	int irq_map_size;
	void (*handle_events)(struct max2035x_plc *plc, unsigned long events);

	struct max2035x_plc_irq_data *irq_data;
	unsigned long pending_events;
	struct work_struct work;
};

struct max2035x_plc_irq_map {
	u8 reg_idx;		/* INT bank index: 0=INT0, 1=INT1, ... */
	u8 mask;		/* BIT(x) */
	unsigned int event;	/* enum max20355_plc_event or enum max20357_plc_event */
};

